export function normalizeFields(fields) {
  if (!Array.isArray(fields)) throw new TypeError('분야 목록을 입력하세요.');
  const labels = fields.map(field => {
    if (typeof field !== 'string' || !field.trim()) {
      throw new TypeError('분야 이름을 입력하세요.');
    }
    return field.normalize('NFKC').trim().replace(/\s+/gu, ' ');
  });
  return [...new Set(labels)];
}
